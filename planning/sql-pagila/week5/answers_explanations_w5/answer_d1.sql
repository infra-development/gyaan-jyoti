-- -----------------------------------------------------
-- Q1
-- Display all customers whose total spending
-- is greater than the average customer spending.
-- -----------------------------------------------------

SELECT
    customer_id,
    SUM(amount) AS total_spending
FROM payment
GROUP BY
    customer_id
HAVING
    SUM(amount) >
    (
        SELECT AVG(customer_total)
        FROM
        (
            SELECT
                SUM(amount) AS customer_total
            FROM payment
            GROUP BY customer_id
        ) AS customer_revenue
    )
ORDER BY
    total_spending DESC;


-- -----------------------------------------------------
-- Q2
-- Display all films whose rental rate
-- is higher than the average rental rate.
-- -----------------------------------------------------

SELECT
    film_id,
    title,
    rental_rate
FROM film
WHERE
    rental_rate >
    (
        SELECT AVG(rental_rate)
        FROM film
    )
ORDER BY
    rental_rate DESC,
    title;


-- -----------------------------------------------------
-- Q3
-- Display the customers who have made
-- the maximum payment.
-- -----------------------------------------------------

SELECT DISTINCT
    c.customer_id,
    c.first_name,
    c.last_name,
    p.amount
FROM customer AS c
INNER JOIN payment AS p
    ON c.customer_id = p.customer_id
WHERE
    p.amount =
    (
        SELECT MAX(amount)
        FROM payment
    )
ORDER BY
    c.customer_id;


-- -----------------------------------------------------
-- Q4
-- Display the films that have never been rented.
-- -----------------------------------------------------

SELECT
    f.film_id,
    f.title
FROM film AS f
WHERE NOT EXISTS
(
    SELECT 1
    FROM inventory AS i
    INNER JOIN rental AS r
        ON i.inventory_id = r.inventory_id
    WHERE i.film_id = f.film_id
)
ORDER BY
    f.title;


-- -----------------------------------------------------
-- Q5
-- Using a derived table, display the
-- total revenue generated by each customer.
-- -----------------------------------------------------

SELECT
    customer_id,
    total_revenue
FROM
(
    SELECT
        customer_id,
        SUM(amount) AS total_revenue
    FROM payment
    GROUP BY
        customer_id
) AS customer_revenue
ORDER BY
    total_revenue DESC;


-- -----------------------------------------------------
-- Q6
-- Using a derived table, display the
-- average revenue generated by each store.
-- -----------------------------------------------------

SELECT
    AVG(store_revenue) AS average_store_revenue
FROM
(
    SELECT
        c.store_id,
        SUM(p.amount) AS store_revenue
    FROM customer AS c
    INNER JOIN payment AS p
        ON c.customer_id = p.customer_id
    GROUP BY
        c.store_id
) AS revenue_by_store;


-- -----------------------------------------------------
-- Q7
-- Explain the difference between a
-- WHERE subquery and a derived table.
-- -----------------------------------------------------

/*

WHERE Subquery

• Returns value(s)
  used for filtering.

• Usually appears in
  WHERE or HAVING.

-------------------------------------

Derived Table

• Returns a temporary
  result set.

• Appears in FROM.

• Can be queried like
  a normal table.

*/


